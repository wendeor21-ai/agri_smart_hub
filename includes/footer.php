// Common utility functions
function showLoading(button) {
    if (!button) return null;
    const originalText = button.innerHTML;
    button.innerHTML = '<span class="spinner-border spinner-border-sm" role="status" aria-hidden="true"></span> Processing...';
    button.disabled = true;
    return originalText;
}

function hideLoading(button, originalText) {
    if (!button || !originalText) return;
    button.innerHTML = originalText;
    button.disabled = false;
}

// Form validation with feedback
function validateForm(form) {
    let isValid = true;
    const inputs = form.querySelectorAll('input[required], select[required], textarea[required]');
    
    inputs.forEach(input => {
        const errorElement = input.nextElementSibling?.classList?.contains('invalid-feedback') 
            ? input.nextElementSibling 
            : null;
        
        if (!input.value.trim()) {
            input.classList.add('is-invalid');
            if (errorElement) {
                errorElement.textContent = 'This field is required';
            }
            isValid = false;
        } else {
            input.classList.remove('is-invalid');
            if (errorElement) {
                errorElement.textContent = '';
            }
        }
        
        // Email validation
        if (input.type === 'email' && input.value.trim()) {
            const emailRegex = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;
            if (!emailRegex.test(input.value)) {
                input.classList.add('is-invalid');
                if (errorElement) {
                    errorElement.textContent = 'Please enter a valid email address';
                }
                isValid = false;
            }
        }
    });
    
    return isValid;
}

// Show notification/toast
function showNotification(message, type = 'info', duration = 5000) {
    const types = {
        success: { icon: 'check-circle', color: '#28a745' },
        error: { icon: 'exclamation-circle', color: '#dc3545' },
        warning: { icon: 'exclamation-triangle', color: '#ffc107' },
        info: { icon: 'info-circle', color: '#17a2b8' }
    };
    
    const config = types[type] || types.info;
    
    // Remove existing notifications
    const existing = document.querySelectorAll('.notification-toast');
    existing.forEach(n => n.remove());
    
    // Create notification
    const notification = document.createElement('div');
    notification.className = `notification-toast notification-${type}`;
    notification.innerHTML = `
        <div class="toast-content">
            <i class="fas fa-${config.icon}"></i>
            <span>${message}</span>
        </div>
        <button class="toast-close" onclick="this.parentElement.remove()">
            <i class="fas fa-times"></i>
        </button>
    `;
    
    document.body.appendChild(notification);
    
    // Auto remove
    setTimeout(() => {
        if (notification.parentNode) {
            notification.style.opacity = '0';
            notification.style.transform = 'translateX(100%)';
            setTimeout(() => notification.remove(), 300);
        }
    }, duration);
}

